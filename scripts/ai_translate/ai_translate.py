#!/usr/bin/env python3
"""Uebersetzt die Gegner-KI-Skriptklassen (BtlAiBasic/Strong/Expert/Double) aus dem Ghidra-Pseudocode nach C# (Kampf-Scheibe 7).

Eingabe: work/decomp/battle_all/Dpr_Battle_Logic_BtlAi<Klasse>.c (Pseudocode, nicht im Repo; nur lesen).
Ausgabe: unity/Assets/Scripts/BattleFlow/Ai/Generated/*.cs (reine Programmausgabe: Kontrollfluss goto-treu, Befehlsfolgen wie im Original).
Statische Zahlenfelder (`InitializeArray`, Wertungstabellen der Typpruefung) liest das Orakel (scripts/battle_oracle.py) aus dem ELF.
Geprueft wird die Ausgabe von scripts/battle_oracle_ai.py gegen die echten ARM64-Funktionen (BattleAiScriptOracleTests).

Aufruf:  PYTHONPATH=tools/pydeps python3 scripts/ai_translate/ai_translate.py [--out DIR]
"""
import argparse
import os
import re
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "scripts"))
import ghc_emit as em  # noqa: E402
import ghc_parse as gp  # noqa: E402

DECOMP = ROOT / "work/decomp/battle_all"
BASE_CS = ROOT / "unity/Assets/Scripts/BattleFlow/Ai/AiScriptBase.cs"
HEADER = ["// <auto-generated> scripts/ai_translate/ai_translate.py uebersetzt die BtlAi*-Skriptfunktionen aus dem Ghidra-Pseudocode; nicht von Hand aendern. </auto-generated>",
          "#pragma warning disable 0162, 0164, 0168, 0219", "", "using System;", "using System.Collections.Generic;", "using static Xnu.Battle.Flow.AiCmd;", "",
          "namespace Xnu.Battle.Flow", "{"]
# bereits von Hand umgesetzte (und gepruefte) Basic-Funktionen: werden nicht uebersetzt, aber aufgerufen (Seq001 usw.)
BASIC_HAND = {1, 7, 10, 11, 12, 13, 16, 18, 19, 20, 28, 32, 33, 35, 37, 47, 49, 65, 84, 92, 106, 109, 115, 132, 136, 148, 158, 160, 188, 211, 212, 225, 251}

_oracle = None


def oracle():
    global _oracle
    if _oracle is None:
        import battle_oracle as bo
        _oracle = (bo, bo.Oracle(), bo.load_dump_arrays())
    return _oracle


def blob_values(ptr_hex):
    bo, o, arrays = oracle()
    raw = o.field_blob(int(ptr_hex, 16), arrays)
    return list(struct.unpack("<%dq" % (len(raw) // 8), raw)) if len(raw) % 8 == 0 else list(raw)


def dat_table(addr_hex, count):
    bo, o, _ = oracle()
    return list(struct.unpack("<%di" % count, o.read(int(addr_hex, 16) - bo.IMAGE_BASE, count * 4)))


def cmd_names():
    """AI_CMD-Nummer -> Konstante in AiCmd (Namen aus AiScriptBase.cs; fehlende Nummern gibt es nicht)."""
    src = BASE_CS.read_text()
    block = src[src.index("class AiCmd"):src.index("class AiScriptBase")]
    return {int(v): n for n, v in re.findall(r"(\w+) = (\d+)", block) if n != "Count"}


def load(cls):
    text = (DECOMP / f"Dpr_Battle_Logic_{cls}.c").read_text()
    fns = {}
    for chunk in re.split(r"\n(?=// 0x)", text):
        m = re.match(r"// 0x[0-9a-f]+ \w+\$\$(\w+)", chunk)
        if m and m.group(1) not in ("_ctor", "_cctor"):
            txt = chunk
            if cls == "BtlAiDouble" and m.group(1) == "DoubleAI_Friend_Main":
                # nicht aufloesbarer Sprungtabellen-Aufruf: KI-Nummern 0x181..0x189 -> Funktion, mit dem Orakel gemessen (Friend: 385, 386->309, 388, 391, 393->309)
                pre = "Dpr_Battle_Logic_BtlAiDouble__DoubleAI_Friend_Seq_"
                old = "(*(code *)((ulong)(byte)(&DAT_03e5a719)[uVar7 & 0xffffffff] * 4 + 0x1d0b9a0))();\n        return;"
                assert old in txt
                new = "switch(uVar7 & 0xffffffff) { " + " ".join(f"case {k}: {pre}{v}(param_1); return;" for k, v in ((0, 385), (1, 309), (3, 388), (6, 391), (8, 309))) + " default: return; }"
                txt = txt.replace(old, new)
            fns[m.group(1)] = txt
    return fns


def translate(cls, names=None):
    texts = load(cls)
    parsed = {k: gp.parse_function(t) for k, t in texts.items() if names is None or k in names}
    rets = {fn["name"]: "void" if fn["ret"] == "void" else em.promote(em.CT.get(fn["ret"], fn["ret"])) for fn in parsed.values()}
    for fn in parsed.values():
        em.FN_PARAMS[fn["name"]] = [em.CT[x.rsplit(" ", 1)[0].replace("*", "").strip()] for x in
                                    [x.strip() for x in fn["params"].split(",") if x.strip() and x.strip() != "void"][1:]]
    cn = cmd_names()
    out = {}
    for k, fn in parsed.items():
        simp = gp.Simplifier(fn)
        simp.blob_fn = blob_values
        body = simp.run()
        e = em.Emitter(fn, body, simp.decls)
        out[k] = (fn, e.run(rets, cn), e.tables, texts[k])
    return out


def entries(out, names):
    ents = [out[k][0] for k in names if not [x for x in out[k][0]["params"].split(",") if x.strip() and x.strip() != "void" and "param_1" not in x]]
    lines = ["        static readonly string[] Names = { " + ", ".join('"%s"' % fn["name"] for fn in ents) + " };", "",
             "        public override IEnumerable<string> Functions => Names;", "", "        public override long Run(string function)", "        {",
             "            switch (function)", "            {"]
    for fn in ents:
        n, r = fn["name"], fn["ret"]
        lines.append(f'                case "{n}": {n}(); return 0;' if r == "void" else f'                case "{n}": return {n}() ? 1 : 0;' if r == "bool" else f'                case "{n}": return (long){n}();')
    return lines + ["            }", "", "            throw new ArgumentException(function);", "        }", ""]


def tables(out, names):
    tabs = {}
    for k in names:
        fn, _, tbls, text = out[k]
        addrs = sorted({int(x, 16) for x in re.findall(r"&DAT_([0-9a-f]+)", text)})
        for t in tbls:
            a = int(t[3:], 16)
            nxt = [x for x in addrs if x > a]
            v = dat_table(t[3:], (nxt[0] - a) // 4 if nxt else 18)
            while v and abs(v[-1]) > 100:     # Rest hinter der letzten Tabelle ist fremder Speicher
                v.pop()
            tabs[t] = v
    return tabs


def write_class(path, cls, csname, summary, with_tables=False):
    out = translate(cls)
    names = sorted(out)
    lines = HEADER + ["    // " + summary, f"    public sealed partial class {csname} : AiScriptBase", "    {"] + entries(out, names)
    if with_tables:
        for t, v in sorted(tables(out, names).items()):
            lines.append(f"        static readonly int[] {t} = {{ " + ", ".join(map(str, v)) + " };")
        lines.append("")
    for k in names:
        lines += out[k][1] + [""]
    path.write_text("\n".join(lines[:-1] + ["    }", "}"]) + "\n")
    return len(names)


def write_basic(path):
    all_names = [k for k in load("BtlAiBasic") if re.fullmatch(r"BaciAI_Seq_(\d+)", k)]
    want = [k for k in all_names if int(k[-3:]) not in BASIC_HAND]
    for n in BASIC_HAND:
        em.FN_RENAME["BaciAI_Seq_%03d" % n] = "Seq%03d" % n
    out = translate("BtlAiBasic", set(want))
    names = sorted(out)
    lines = HEADER + ["    // BtlAiBasic: die uebrigen BaciAI_Seq_NNN-Funktionen, aus dem Pseudocode uebersetzt (die von Hand umgesetzten stehen in AiScriptBasic.cs).",
                      "    public sealed partial class AiScriptBasic", "    {", "        partial void RegisterGenerated()", "        {"]
    lines += [f'            ImplementedSeq.Add({int(n[-3:])}); _seq[{int(n[-3:])}] = {n}; _entries["{n}"] = () => {{ {n}(); return 0; }};' for n in names]
    lines += ["        }", ""]
    for k in names:
        lines += out[k][1] + [""]
    path.write_text("\n".join(lines[:-1] + ["    }", "}"]) + "\n")
    return len(names)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(ROOT / "unity/Assets/Scripts/BattleFlow/Ai/Generated"))
    ns = ap.parse_args()
    out = Path(ns.out)
    out.mkdir(parents=True, exist_ok=True)
    print("Double", write_class(out / "AiScriptDouble.cs", "BtlAiDouble", "AiScriptDouble", "BtlAiDouble (AI-Bit 8): Partner-/Doppelkampf-Wertung."))
    print("Expert", write_class(out / "AiScriptExpert.cs", "BtlAiExpert", "AiScriptExpert", "BtlAiExpert (AI-Bit 4): umfangreiche Attackenwertung.", True))
    print("Strong", write_class(out / "AiScriptStrongFull.cs", "BtlAiStrong", "AiScriptStrongFull", "BtlAiStrong (AI-Bit 2): Zusatzwertung (Einzel-, Doppel- und G-Zweig)."))
    print("Basic", write_basic(out / "AiScriptBasicGen.cs"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
