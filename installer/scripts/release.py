#!/usr/bin/env python3
"""Plan explicit installer releases and collect verified native build artifacts."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[2]
TARGETS = ("macos-aarch64", "macos-x86_64", "linux-aarch64", "linux-x86_64", "windows-x86_64")
SBOM = ("sbom-strahlender-xnu.spdx.json", "sbom-strahlender-xnu.spdx", "sbom-strahlender-xnu.cdx.json", "sbom-strahlender-xnu.csv")
UPDATE = ("installer-update.json", "installer-update.json.sig")
# Which public download updates which installer (the installer's own host name); one universal zip serves both Macs.
UPDATE_TARGETS = {
    "macos-aarch64": "installer-macos-universal.zip",
    "macos-x86_64": "installer-macos-universal.zip",
    "linux-aarch64": "Strahlender-Installer-aarch64.AppImage",
    "linux-x86_64": "Strahlender-Installer-x86_64.AppImage",
    "windows-x86_64": "installer-windows-x86_64.zip",
}
PACKAGES = ("installer-macos-universal.zip", "Strahlender-Installer-aarch64.AppImage", "Strahlender-Installer-x86_64.AppImage",
            "installer-windows-x86_64.zip")


def plan(version, event, ref, channel, revision, run_id, attempt, draft=False):
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        raise ValueError("Installer Cargo version must be a stable three-part version.")
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("Expected the exact source commit SHA.")
    if event == "push":
        if ref != "installer-v" + version:
            raise ValueError("Installer release tag must match installer/Cargo.toml.")
        channel = "release"
    elif event != "workflow_dispatch":
        raise ValueError("Only a manual run or an explicit installer release tag can publish.")
    if channel not in ("artifacts", "nightly", "release"):
        raise ValueError("Unknown installer channel.")
    if channel == "nightly":
        if not run_id.isdigit() or not attempt.isdigit():
            raise ValueError("Expected numeric GitHub run identifiers.")
        tag = f"installer-nightly-{run_id}-{attempt}"
    elif channel == "release":
        tag = "installer-v" + version
    else:
        tag = ""
    return {"channel": channel, "version": version, "tag": tag, "revision": revision, "draft": draft}


def collect(artifacts, output, release):
    if output.exists():
        raise ValueError("Release staging directory already exists.")
    inventory = {}
    for name in PACKAGES:
        matches = list(artifacts.rglob(name))
        if len(matches) != 1 or not matches[0].is_file() or matches[0].is_symlink():
            raise ValueError(f"Expected exactly one regular artifact: {name}")
        source = matches[0]
        checksum_file = source.parent / "SHA256SUMS"
        entries = {}
        for line in checksum_file.read_text().splitlines():
            digest, filename = line.split(maxsplit=1)
            entries[filename.lstrip("*")] = digest
        with source.open("rb") as file:
            digest = hashlib.file_digest(file, "sha256").hexdigest()
        if entries.get(name) != digest:
            raise ValueError(f"Artifact checksum mismatch: {name}")
        inventory[name] = (source, digest)
    output.mkdir(parents=True)
    for name, (source, _) in inventory.items():
        shutil.copy2(source, output / name)
    for name in SBOM:  # generated by the sbom job; optional so local collects still work
        found = [m for m in artifacts.rglob(name) if m.is_file() and not m.is_symlink()]
        if len(found) == 1:
            shutil.copy2(found[0], output / name)
    (output / "SHA256SUMS").write_text("".join(
        f"{digest}  {name}\n" for name, (_, digest) in sorted(inventory.items())))
    internal = output / ".internal"
    internal.mkdir()
    (internal / "installer-build.json").write_text(json.dumps(
        {"schema": 1, **release, "targets": TARGETS}, indent=2) + "\n")


def sign_update(folder, version, seed_b64, public_key_b64):
    """Writes installer-update.json (every target with the SHA-256 of its download) and its Ed25519 signature.
    The installer verifies both against the public key built into it (installer/src/updates.rs)."""
    import base64
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        raise ValueError("Installer Cargo version must be a stable three-part version.")
    seed = base64.b64decode(seed_b64.strip(), validate=True)
    if len(seed) != 32:
        raise ValueError("Expected a base64-encoded 32-byte Ed25519 seed.")
    key = Ed25519PrivateKey.from_private_bytes(seed)
    # The installers carry the public key from the repository variable; a different secret would sign updates nobody accepts.
    derived = base64.b64encode(key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)).decode()
    if not public_key_b64 or derived != public_key_b64.strip():
        raise ValueError("The signing key does not match INSTALLER_UPDATE_PUBLIC_KEY: installers built with that key would reject the update.")
    assets = []
    for target, name in UPDATE_TARGETS.items():
        path = folder / name
        if not path.is_file() or path.is_symlink():
            raise ValueError(f"Missing download for {target}: {name}")
        with path.open("rb") as file:
            digest = hashlib.file_digest(file, "sha256").hexdigest()
        assets.append({"target": target, "name": name, "sha256": digest})
    manifest = (json.dumps({"version": version, "assets": assets}, indent=2) + "\n").encode()
    signature = base64.b64encode(key.sign(manifest))
    (folder / UPDATE[0]).write_bytes(manifest)
    (folder / UPDATE[1]).write_bytes(signature)


def release_notes(release, repository):
    version = release["version"]
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        raise ValueError("Invalid release version.")
    path = ROOT / "installer/releases" / (version + ".md")
    if not path.is_file():
        raise ValueError(f"Write installer/releases/{version}.md before publishing this version.")
    notes = path.read_text().rstrip()
    for name in PACKAGES:
        link = f"https://github.com/{repository}/releases/download/{release['tag']}/{name}"
        notes = notes.replace(f"`{name}`", f"[{name}]({link})")
    return notes + (
        "\n\nThe `sbom-*` files are the software bill of materials for auditors and compliance tools. You do not need them to use the installer.\n"
        f"\n---\nChannel: **{release['channel']}** · "
        f"[Installer source](https://github.com/{repository}/commit/{release['revision']})\n")


def publish(folder, release, repository):
    if release["channel"] == "artifacts":
        raise ValueError("Artifact-only runs must never publish a GitHub release.")
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
        raise ValueError("Invalid GitHub repository.")
    tag = release["tag"]
    # A stable tag may already exist; it must refer to this exact source revision.
    existing = subprocess.run(["git", "ls-remote", "origin", f"refs/tags/{tag}",
                               f"refs/tags/{tag}^{{}}"], check=True, capture_output=True, text=True)
    refs = dict(line.split()[::-1] for line in existing.stdout.splitlines())
    tagged = refs.get(f"refs/tags/{tag}^{{}}", refs.get(f"refs/tags/{tag}"))
    if tagged and tagged != release["revision"]:
        raise ValueError("Existing release tag points to a different commit. Tags are never moved.")
    prerelease = release["channel"] == "nightly"
    title = ("Installer nightly · " + release["revision"][:8] if prerelease
             else "Strahlender Installer " + release["version"])
    notes = release_notes(release, repository)
    with tempfile.TemporaryDirectory(prefix="installer-release-notes-") as temporary:
        path = Path(temporary) / "notes.md"
        path.write_text(notes)
        command = ["gh", "release", "create", tag, "--repo", repository,
                   "--target", release["revision"], "--draft", "--title", title,
                   "--notes-file", str(path)]
        if prerelease:
            command.append("--prerelease")
        command.extend(str(folder / name) for name in (*PACKAGES, "SHA256SUMS", *(n for n in (*SBOM, *UPDATE) if (folder / n).exists())))
        subprocess.run(command, check=True)
    if release.get("draft", False):
        return
    # Upload every artifact before exposing the release. Stable releases become
    # latest explicitly; nightly builds never replace the stable latest link.
    subprocess.run(["gh", "release", "edit", tag, "--repo", repository,
                    "--draft=false", "--latest=" + ("false" if prerelease else "true")], check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    planning = sub.add_parser("plan")
    planning.add_argument("--event", required=True)
    planning.add_argument("--ref", required=True)
    planning.add_argument("--channel", default="artifacts")
    planning.add_argument("--draft", choices=("true", "false"), default="false")
    planning.add_argument("--revision", required=True)
    planning.add_argument("--run-id", required=True)
    planning.add_argument("--attempt", required=True)
    planning.add_argument("--github-output", type=Path, required=True)
    assembling = sub.add_parser("collect")
    assembling.add_argument("--artifacts", type=Path, required=True)
    assembling.add_argument("--output", type=Path, required=True)
    assembling.add_argument("--plan", type=Path, required=True)
    signing = sub.add_parser("sign", help="Sign the update manifest (seed in the environment variable INSTALLER_UPDATE_SEED).")
    signing.add_argument("--folder", type=Path, required=True)
    signing.add_argument("--plan", type=Path, required=True)
    publishing = sub.add_parser("publish")
    publishing.add_argument("--folder", type=Path, required=True)
    publishing.add_argument("--plan", type=Path, required=True)
    publishing.add_argument("--repository", required=True)
    args = parser.parse_args()
    if args.command == "plan":
        version = tomllib.loads((ROOT / "installer/Cargo.toml").read_text())["package"]["version"]
        release = plan(version, args.event, args.ref, args.channel, args.revision, args.run_id, args.attempt,
                       args.draft == "true")
        if release["channel"] != "artifacts":
            release_notes(release, "Veemyu/strahlender-xnu")
        Path("installer-release-plan.json").write_text(json.dumps(release) + "\n")
        with args.github_output.open("a") as file:
            for key, value in release.items():
                file.write(f"{key}={value}\n")
    elif args.command == "sign":
        seed = os.environ.get("INSTALLER_UPDATE_SEED", "")
        if not seed:
            raise SystemExit("INSTALLER_UPDATE_SEED is not set: a stable release must carry a signed update manifest.")
        sign_update(args.folder, json.loads(args.plan.read_text())["version"], seed, os.environ.get("INSTALLER_UPDATE_PUBLIC_KEY", ""))
    elif args.command == "collect":
        collect(args.artifacts, args.output, json.loads(args.plan.read_text()))
    else:
        publish(args.folder, json.loads(args.plan.read_text()), args.repository)


if __name__ == "__main__":
    main()
